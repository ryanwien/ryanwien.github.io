"""Rendering for ``results/``: the metrics JSON and the Markdown report.

Pure functions of a note and its summary; nothing here decides what is proven.
"""

from dataclasses import replace
from typing import Any

from thesistrace.domain import Evidence, ResearchNote
from thesistrace.summary import EvidenceSummary, summarize

LABELS = {
    Evidence.SUPPORTED: "Supported",
    Evidence.MIXED: "Mixed",
    Evidence.UNVERIFIED: "Unverified",
}


def metrics(note: ResearchNote, summary: EvidenceSummary, tests: int) -> dict[str, Any]:
    """Machine-readable numbers for ``results/metrics.json``."""
    return {
        "note": note.id,
        "assumptions": summary.total,
        "counts": {label.value: summary.counts[label] for label in Evidence},
        "shares_percent": {label.value: summary.shares[label] for label in Evidence},
        "critical_open": summary.critical_open,
        "verdict": summary.verdict.value,
        "supported_share_as_built": supported_share_as_built(note),
        "tests": tests,
    }


def markdown(note: ResearchNote, summary: EvidenceSummary) -> str:
    """The human report for ``results/REPORT.md``."""
    by_id = {a.id: a for a in note.assumptions}
    lines = [
        "# ThesisTrace: sample note",
        "",
        "Generated by `python -m thesistrace.run`. Do not edit by hand.",
        "",
        f"**Question.** {note.question}",
        "",
        f"**Tentative conclusion.** {note.conclusion}",
        "",
        f"**Verdict.** {summary.headline}",
        "",
        "| Label | Assumptions | Share |",
        "|---|---:|---:|",
    ]
    lines += [
        f"| {LABELS[label]} | {summary.counts[label]} | {summary.shares[label]}% |"
        for label in Evidence
    ]
    for title, ids in (
        ("Proven", summary.proven),
        ("Uncertain", summary.uncertain),
        ("Needs a source", summary.needs_source),
    ):
        lines += ["", f"## {title}", ""]
        if not ids:
            lines.append("None.")
        for assumption_id in ids:
            item = by_id[assumption_id]
            flag = " **(load-bearing)**" if item.critical else ""
            cite = f" Source: {item.source}." if item.source else ""
            lines.append(f"- {item.statement}{flag}{cite}")
    return "\n".join(lines) + "\n"


def supported_share_as_built(note: ResearchNote) -> list[int]:
    """Supported share (%) of the note after each assumption was added, in order."""
    return [
        summarize(replace(note, assumptions=note.assumptions[:n])).shares[Evidence.SUPPORTED]
        for n in range(1, len(note.assumptions) + 1)
    ]
